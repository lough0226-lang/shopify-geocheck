<p>开发者问 AI 助手某个库怎么用时，一份整理干净的文档索引能省掉助手爬整个网站。Anthropic 的 Claude Code 文档明确让智能体先去取它的 llms.txt 索引。OpenAI、Anthropic 和 Google 都为自己的开发者文档发布了这个文件。Ahrefs 在它的数据里发现，Claude Code 取 llms.txt 的次数比任何一个 AI 检索机器人都多。</p>
