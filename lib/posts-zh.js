<p>当这些事实缺席时，价格就成了手边最可靠的信号。而价格还和另一件跟质量无关的东西相关：完整度。大品牌的产品页往往更周全，填的属性更多，可检索的文字更多。所以一个追求确定性的 AI，会系统性地偏向资料更全的那个产品，而它不成比例地就是更贵的那个。消费者的体验就是它推了贵的那个。机制不是贿赂，是输入里的一个空洞。</p>
