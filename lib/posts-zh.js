<p>改后：ErgoPro 500 采用 42 厘米宽网布靠背，腰托可调，高度范围 15 到 22 厘米；50 厘米座深，3 英寸高密度泡棉坐垫；靠背可后仰至 135 度，5 档倾仰锁定。承重上限 120 公斤。五星尼龙底座，60 毫米顺滑轮。</p>
