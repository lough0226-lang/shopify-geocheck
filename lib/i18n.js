import { useState, useEffect } from 'react';

export const LANGUAGES = {
  en: { code: 'en', label: 'English', flag: '🇺🇸' },
  de: { code: 'de', label: 'Deutsch', flag: '🇩🇪' },
  fr: { code: 'fr', label: 'Français', flag: '🇫🇷' },
  es: { code: 'es', label: 'Español', flag: '🇪🇸' },
  pt: { code: 'pt', label: 'Português', flag: '🇧🇷' },
  zh: { code: 'zh', label: '中文', flag: '🇨🇳' },
};

export function useLang() {
  const [lang, setLang] = useState('en');
  useEffect(() => {
    try {
      const saved = localStorage.getItem('geo_lang');
      if (saved && LANGUAGES[saved]) setLang(saved);
    } catch (e) {}
    function handleChange(e) {
      if (e.detail && e.detail.lang) setLang(e.detail.lang);
    }
    window.addEventListener('languagechange', handleChange);
    return () => window.removeEventListener('languagechange', handleChange);
  }, []);
  return lang;
}

